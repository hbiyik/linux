#define RK610_AUDIO_SAMPLE_RATE_1764K 0xc
#define RK610_AUDIO_SAMPLE_RATE_192K 0xe

#define RK610_HDMI_REG_AUDIO_I2S_MODE 0x38
#define RK610_AUDIO_I2S_CHANNEL(n) ((n) << 2)
#define RK610_AUDIO_I2S_CHANNEL_1_2 1
#define RK610_AUDIO_I2S_CHANNEL_3_4 3
#define RK610_AUDIO_I2S_CHANNEL_5_6 7
#define RK610_AUDIO_I2S_CHANNEL_7_8 0xf
#define RK610_AUDIO_I2S_MODE_STANDARD 0
#define RK610_AUDIO_I2S_MODE_LEFT_JUSTIFIED 1
#define RK610_AUDIO_I2S_MODE_RIGHT_JUSTIFIED 2

#define RK610_HDMI_REG_AUDIO_I2S_MAP 0x39
#define RK610_HDMI_REG_AUDIO_I2S_SWAPS_SPDIF 0x3a
#define RK610_AUDIO_SPDIF_FREQ(n) (n)

#define RK610_AUDIO_N_32K 0x1000
#define RK610_AUDIO_N_441K 0x1880
#define RK610_AUDIO_N_882K 0x3100
#define RK610_AUDIO_N_1764K 0x6200
#define RK610_AUDIO_N_48K 0x1800
#define RK610_AUDIO_N_96K 0x3000
#define RK610_AUDIO_N_192K 0x6000

#define RK610_HDMI_REG_AUDIO_N_H 0x3f
#define RK610_HDMI_REG_AUDIO_N_M 0x40
#define RK610_HDMI_REG_AUDIO_N_L 0x41

#define RK610_HDMI_REG_AUDIO_CTS_H 0x45
#define RK610_HDMI_REG_AUDIO_CTS_M 0x46
#define RK610_HDMI_REG_AUDIO_CTS_L 0x47

#define RK610_HDMI_REG_OUTPUT_MODE 0x52
#define RK610_HDMI_OUTPUT_DVI 0x00
#define RK610_HDMI_OUTPUT_HDMI 0x02

#define RK610_HDMI_REG_CONTROL_PACKET_BUF_INDEX 0x9f
#define RK610_HDMI_INFOFRAME_AVI 0x06
#define RK610_HDMI_INFOFRAME_AAI 0x08
#define RK610_HDMI_REG_CONTROL_PACKET_ADDR 0xa0

#endif /* __RK610_HDMI_H__ */
